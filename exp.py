"""Experiment 7: Perceptron and Forward Propagation"""

import numpy as np
import matplotlib.pyplot as plt

np.random.seed(42)

def step(z):
    return (z >= 0).astype(int)

def predict(X, w, b):
    z = np.dot(X, w) + b
    return step(z)

credit = np.random.randint(300, 851, 100)
income_ratio = np.random.uniform(0.1, 0.9, 100)

X = np.column_stack((credit / 850, income_ratio))

y = ((X[:, 0] + X[:, 1]) >= 1.1).astype(int)

def train(X, y, epochs=30):
    w = np.zeros(X.shape[1])
    b = 0.0
    history = []

    for epoch in range(epochs):
        errors = 0

        for i in range(len(X)):
            output = predict(X[i], w, b)
            error = y[i] - output

            w = w + 0.1 * error * X[i]
            b = b + 0.1 * error

            if error != 0:
                errors += 1

        history.append(errors)
        print("Epoch", epoch + 1,
              "Updates:", errors,
              "Weights:", np.round(w, 3),
              "Bias:", round(b, 3))

        if errors == 0:
            break

    return w, b, history

w, b, history = train(X, y)

print("\nFinal Weights:", w)
print("Final Bias:", b)
print("Training Accuracy:",
      np.mean(predict(X, w, b) == y))

plt.figure(figsize=(7, 5))

plt.scatter(X[:, 0], X[:, 1], c=y, cmap="bwr")

x_line = np.linspace(0.3, 1.0, 100)
