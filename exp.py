import numpy as np
import matplotlib.pyplot as plt

def loss_function(x, y):
    return x**2 + 4 * y**2

def gradients(x, y):
    df_dx = 2 * x
    df_dy = 8 * y
    return np.array([df_dx, df_dy])

def batch_gradient_descent(start_pos, lr, epochs):
    path = [start_pos]
    pos = np.array(start_pos, dtype=float)
    for _ in range(epochs):
        grad = gradients(pos[0], pos[1])
        pos -= lr * grad
        path.append(pos.copy())
    return np.array(path)

def stochastic_gradient_descent(start_pos, lr, epochs, noise_level=1.5):
    path = [start_pos]
    pos = np.array(start_pos, dtype=float)
    for _ in range(epochs):
        grad = gradients(pos[0], pos[1]) + np.random.normal(0, noise_level, 2)
        pos -= lr * grad
        path.append(pos.copy())
    return np.array(path)

def momentum_gradient_descent(start_pos, lr, beta, epochs):
    path = [start_pos]
    pos = np.array(start_pos, dtype=float)
    velocity = np.zeros(2)
    for _ in range(epochs):
        grad = gradients(pos[0], pos[1])
        velocity = beta * velocity + lr * grad
        pos -= velocity
        path.append(pos.copy())
    return np.array(path)

